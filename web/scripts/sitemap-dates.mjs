// Writes app/sitemap-dates.ts: the real "last changed" date of each kind of page, taken from the git history of the
// files that hold its content. The sitemap used to say every page changed "now", which makes Google ignore lastmod.
// Run `npm run sitemap:dates` before a deploy when content has changed, and commit the result.
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";

const today = new Date().toISOString().slice(0, 10);
const day = (files) => {
  let best = "";
  for (const f of files) {
    try {
      // A file with uncommitted changes counts as changed today.
      if (execFileSync("git", ["status", "--porcelain", "--", f], { encoding: "utf8" }).trim()) {
        best = today;
        continue;
      }
      const d = execFileSync("git", ["log", "-1", "--format=%cs", "--", f], { encoding: "utf8" }).trim();
      if (d > best) best = d;
    } catch {
      /* not a git checkout */
    }
  }
  return best;
};

const page = (route) => `app${route}/page.tsx`;
const statics = ["/features", "/how-it-works", "/pricing", "/use-cases", "/tools", "/fix", "/blog", "/consultation", "/faq", "/about", "/contact", "/bot", "/privacy", "/terms"];
const groups = {
  "/fix/": ["lib/scan/guides.ts", "app/fix/[id]/page.tsx", "app/fix/guide-browser.tsx"],
  "/features/": ["app/features-data.ts", "app/features/[slug]/page.tsx"],
  "/blog/": ["app/blog-data.ts", "app/blog-posts-google.ts", "app/blog-posts-more.ts", "app/blog/[slug]/page.tsx"],
  "/tools/": ["app/tools/catalog.ts", "app/tools/[slug]/page.tsx"],
};

const out = { "": day(["app/page.tsx", "app/home-parts.tsx", "app/content.ts"]) };
for (const r of statics) out[r] = day([page(r)]);
for (const [k, files] of Object.entries(groups)) out[k] = day(files);
const fallback = day(["."]) || new Date().toISOString().slice(0, 10);

const rows = Object.entries(out).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v || fallback)},`).join("\n");
writeFileSync(
  "app/sitemap-dates.ts",
  `// Generated by scripts/sitemap-dates.mjs from git history. Do not edit by hand; run \`npm run sitemap:dates\`.
// A key ending in "/" covers every page under it (for example "/blog/" for each post).
export const SITEMAP_DATES: Record<string, string> = {
${rows}
};
export const SITEMAP_DEFAULT_DATE = ${JSON.stringify(fallback)};
`
);
console.log(`wrote app/sitemap-dates.ts (${Object.keys(out).length} entries)`);
